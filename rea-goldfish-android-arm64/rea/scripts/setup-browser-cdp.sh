#!/data/data/com.termux/files/usr/bin/bash
# Enable REA's browser tools on Android/arm64.
#
# REA browser tools (list_browser_targets, inspect_web_page,
# capture_browser_scenario, ...) need one of:
#   1. a Chromium-compatible executable (REA_BROWSER_EXECUTABLE), or
#   2. a Chrome DevTools Protocol endpoint on LOOPBACK (normally 127.0.0.1:9222).
#
# Termux's package set has no usable headless Chromium (the tur-repo chromium
# needs gtk3/libevdev/libxkbcommon, which are not available here). The reliable
# route on a phone is to forward a CDP port from another machine to loopback.
set -uo pipefail
HOME_DIR="/data/data/com.termux/files/home"
mkdir -p "$HOME_DIR/tools/bin"
ENV_FILE="$HOME_DIR/.rea-browser-env.sh"
FORWARDER="$HOME_DIR/tools/bin/rea-browser-cdp-forward"

cat > "$FORWARDER" <<'EOF'
#!/data/data/com.termux/files/usr/bin/bash
# Forward a remote Chrome DevTools Protocol port to this phone's loopback.
# Usage: rea-browser-cdp-forward <user@host> [remote_port] [local_port]
set -eu
if [ "$#" -lt 1 ]; then
  echo "usage: rea-browser-cdp-forward <user@host> [remote_port=9222] [local_port=9222]" >&2
  exit 2
fi
remote="${1}"; rport="${2:-9222}"; lport="${3:-9222}"
echo "Forwarding 127.0.0.1:${lport} -> ${remote}:${rport} (Ctrl-C to stop)"
exec ssh -N -o ExitOnForwardFailure=yes -L "${lport}:127.0.0.1:${rport}" "$remote"
EOF
chmod +x "$FORWARDER"

local_browser=""
for c in chromium chromium-browser google-chrome chrome; do
  if command -v "$c" >/dev/null 2>&1; then local_browser="$(command -v "$c")"; break; fi
done

{
  echo "# REA browser configuration (generated by scripts/setup-browser-cdp.sh)"
  if [ -n "${REA_BROWSER_EXECUTABLE:-}" ]; then
    echo "export REA_BROWSER_EXECUTABLE=\"$REA_BROWSER_EXECUTABLE\""
  elif [ -n "$local_browser" ]; then
    echo "export REA_BROWSER_EXECUTABLE=\"$local_browser\""
  else
    echo "# No local Chromium found. Start the CDP forwarder, then use loopback target 9222:"
    echo "#   $FORWARDER user@desktop 9222 9222"
    echo "#   # then in OpenCode: list_browser_targets { endpoint: \"http://127.0.0.1:9222\" }"
  fi
  echo "export REA_BROWSER_CDP_ENDPOINT=\"http://127.0.0.1:9222\""
} > "$ENV_FILE"

echo "== REA browser setup =="
echo "  forwarder: $FORWARDER"
echo "  env file:  $ENV_FILE"
echo "  local browser: ${local_browser:-none found}"
echo
echo "To use a browser from OpenCode:"
echo "  1. On the remote machine start Chrome with --remote-debugging-port=9222"
echo "  2. On the phone: $FORWARDER user@remote 9222 9222"
echo "  3. In OpenCode:  list_browser_targets { endpoint: \"http://127.0.0.1:9222\" }"
echo "     or          capture_browser_scenario { browser:{mode:\"connect\",endpoint:\"http://127.0.0.1:9222\"}, ... }"
echo
echo "Then add to ~/.bashrc: . $ENV_FILE  (and restart OpenCode so the MCP env is reloaded)"
